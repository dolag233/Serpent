/**
 * Widen leaf literals to `string` while keeping the zh-CN key tree.
 * `typeof zhCN` would require English values to equal Chinese literals.
 */
type CatalogMessages<T> = {
  readonly [K in keyof T]: T[K] extends string
    ? string
    : CatalogMessages<T[K]>;
};

