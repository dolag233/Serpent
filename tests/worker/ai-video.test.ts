describe('OpenAIVendorAdapter with contactSheetBase64', () => {
  it('includes both imageBase64 and contactSheetBase64 in the user message', async () => {
    // Use a mock fetch that captures the request body for inspection.
    let capturedBody: string | null = null;
    const capturingFetch: typeof fetch = ((
      _url: string | URL | Request,
      init?: RequestInit,
    ) => {
      capturedBody = (init?.body as string) ?? null;
      return Promise.resolve({
        status: 200,
        headers: new Map([['Content-Type', 'application/json']]),
        json: () =>
          Promise.resolve({
            choices: [
              {
                message: {
                  content: JSON.stringify({
                    description: 'Captured',
                    tags: [],
                    modelVersion: 'gpt-4o-2024-05-13',
                  }),
                },
              },
            ],
            model: 'gpt-4o-2024-05-13',
          }),
        text: () => Promise.resolve(''),
        ok: true,
      } as unknown as Response);
    }) as unknown as typeof fetch;

    const request: AiAnalysisRequest = {
      filename: 'test-video.mp4',
      mime: 'image/jpeg',
      imageBase64: 'cG9zdGVyQnl0ZXM=',   // base64 of 'posterBytes'
      contactSheetBase64: 'c2hlZXRCeXRlcw==', // base64 of 'sheetBytes'
      language: 'en',
      enabledFields: { description: true, tags: true, rating: false },
      existingTagNames: [],
    };

    const adapter = new OpenAIVendorAdapter('test-key', 'gpt-4o', capturingFetch);
    await adapter.analyze(request);

    expect(capturedBody).not.toBeNull();
    const body = JSON.parse(capturedBody!);

    // Verify both images are in the user message content array.
    const userMessage = body.messages.find(
      (m: { role: string }) => m.role === 'user',
    );
    expect(userMessage).toBeDefined();
    const content = userMessage.content as Array<Record<string, unknown>>;

    // First element: text.
    expect(content[0]!.type).toBe('text');

    // Second element: poster image.
    const posterPart = content[1] as Record<string, unknown>;
    expect(posterPart.type).toBe('image_url');
    const posterUrl = (posterPart.image_url as Record<string, string>).url as string;
    expect(posterUrl).toContain('data:image/jpeg;base64,cG9zdGVyQnl0ZXM=');

    // Third element: contact sheet image.
    const sheetPart = content[2] as Record<string, unknown>;
    expect(sheetPart.type).toBe('image_url');
    const sheetUrl = (sheetPart.image_url as Record<string, string>).url as string;
    expect(sheetUrl).toContain('data:image/png;base64,c2hlZXRCeXRlcw==');

    // The text part should mention the contact sheet instruction.
    const textContent = content[0] as Record<string, unknown>;
    expect(textContent.text).toContain('contact sheet of key frames');
  });

  it('omits contact sheet instruction when only imageBase64 is provided (image mode)', async () => {
    let capturedBody: string | null = null;
    const capturingFetch: typeof fetch = ((_url: string | URL | Request, init?: RequestInit) => {
      capturedBody = (init?.body as string) ?? null;
      return Promise.resolve({
        status: 200,
        headers: new Map([['Content-Type', 'application/json']]),
        json: () =>
          Promise.resolve({
            choices: [{ message: { content: '{"description":"Img","tags":[]}' } }],
            model: 'gpt-4o',
          }),
        text: () => Promise.resolve(''),
        ok: true,
      } as unknown as Response);
    }) as unknown as typeof fetch;

    const request: AiAnalysisRequest = {
      filename: 'photo.png',
      mime: 'image/png',
      imageBase64: 'aW1hZ2VEYXRh',
      language: 'en',
      enabledFields: { description: false, tags: true, rating: false },
      existingTagNames: [],
    };

    const adapter = new OpenAIVendorAdapter('test-key', 'gpt-4o', capturingFetch);
    await adapter.analyze(request);

    const body = JSON.parse(capturedBody!);
    const userMessage = body.messages.find(
      (m: { role: string }) => m.role === 'user',
    );
    const content = userMessage.content as Array<Record<string, unknown>>;

    // Only one image part (poster), no contact sheet.
    const imageParts = content.filter((c) => c.type === 'image_url');
    expect(imageParts).toHaveLength(1);

    // Text should NOT mention contact sheet.
    const textPart = content[0] as Record<string, unknown>;
    expect(textPart.text).not.toContain('contact sheet');
  });
});

