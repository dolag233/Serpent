function makeMockFetch(body: unknown, status = 200): typeof fetch {
  const text = typeof body === 'string' ? body : JSON.stringify(body);
  return (() =>
    Promise.resolve({
      status,
      headers: new Map([['Content-Type', 'application/json']]),
      json: () => Promise.resolve(body),
      text: () => Promise.resolve(text),
      ok: status >= 200 && status < 300,
    } as unknown as Response)) as unknown as typeof fetch;
}

function mockOpenAiFetchForAnalysis(result: AiAnalysisResult): typeof fetch {
  const responseBody = {
    choices: [
      {
        message: {
          content: JSON.stringify({
            description: result.description,
            tags: result.tags,
            rating: (result as { rating?: number }).rating ?? null,
          }),
        },
      },
    ],
    model: result.modelVersion,
  };
  return makeMockFetch(responseBody, 200);
}

