describe('video AI analysis — full flow with ready artifacts', () => {
  it('builds AiAnalysisRequest with poster (imageBase64) and contact sheet (contactSheetBase64)', async () => {
    const root = temporaryRoot();
    const service = new LibraryService();
    const created = service.createLibrary({
      displayName: 'VideoFull',
      selectedParentPath: root,
    });

    // Import a video asset.
    writeFileSync(path.join(root, 'showreel.mp4'), 'video-data');
    const importResult = importNoConflict(
      service,
      created.libraryId,
      path.join(root, 'showreel.mp4'),
    );
    const assetId = importResult.assets[0]!.assetId;

    // Get the current revision id.
    const db = new Database(
      path.join(created.libraryPath, '.serpent', 'library.db'),
    );
    const asset = db
      .prepare('SELECT current_revision_id FROM assets WHERE asset_id = ?')
      .get(assetId) as { current_revision_id: string | null };
    const revisionId = asset.current_revision_id!;

    // Create artifact files in the .serpent/artifacts directory.
    const artifactsDir = path.join(created.libraryPath, '.serpent', 'artifacts');
    mkdirSync(artifactsDir, { recursive: true });

    // Poster artifact.
    const posterId = randomUUID();
    const posterFile = `${posterId}.jpg`;
    const posterBytes = VALID_1X1_JPEG;
    writeFileSync(path.join(artifactsDir, posterFile), posterBytes);
    db.prepare(
      `INSERT INTO revision_artifacts
         (artifact_id, revision_id, kind, mime_type, byte_size, file_path,
          generator_version, status, generated_at)
       VALUES (?, ?, 'video_poster', 'image/jpeg', ?, ?, 'test', 'ready', ?)`,
    ).run(posterId, revisionId, posterBytes.length, posterFile,
      new Date().toISOString());

    // Contact sheet artifact.
    const sheetId = randomUUID();
    const sheetFile = `${sheetId}.jpg`;
    const sheetBytes = VALID_1X1_JPEG;
    writeFileSync(path.join(artifactsDir, sheetFile), sheetBytes);
    db.prepare(
      `INSERT INTO revision_artifacts
         (artifact_id, revision_id, kind, mime_type, byte_size, file_path,
          generator_version, status, generated_at)
       VALUES (?, ?, 'contact_sheet', 'image/jpeg', ?, ?, 'test', 'ready', ?)`,
    ).run(sheetId, revisionId, sheetBytes.length, sheetFile,
      new Date().toISOString());

    // Also insert extracted_metadata artifact for contactSheetDescription.
    const metaId = randomUUID();
    const metaFile = `${metaId}.json`;
    const metadataContent = JSON.stringify({
      durationMs: 12500,
      width: 1920,
      height: 1080,
      videoCodec: 'h264',
    });
    writeFileSync(path.join(artifactsDir, metaFile), metadataContent, 'utf-8');
    db.prepare(
      `INSERT INTO revision_artifacts
         (artifact_id, revision_id, kind, mime_type, byte_size, file_path,
          generator_version, status, generated_at)
       VALUES (?, ?, 'extracted_metadata', 'application/json', ?, ?, 'test', 'ready', ?)`,
    ).run(metaId, revisionId, Buffer.byteLength(metadataContent, 'utf-8'),
      metaFile, new Date().toISOString());

    db.close();

    // Simulate the video analysis flow as index.ts does it.
    const { filePath } = service.resolveAssetFilePath(created.libraryId, assetId);

    // 1) Get artifacts.
    const contactSheet = service.getCurrentArtifact(
      created.libraryId, assetId, 'contact_sheet',
    );
    expect(contactSheet).not.toBeNull();
    expect(contactSheet!.status).toBe('ready');

    const poster = service.getCurrentArtifact(
      created.libraryId, assetId, 'video_poster',
    );
    expect(poster).not.toBeNull();
    expect(poster!.status).toBe('ready');

    // 2) Read artifact bytes.
    const posterAbsPath = service.getArtifactAbsolutePath(
      created.libraryId, poster!.artifactId,
    );
    const sheetAbsPath = service.getArtifactAbsolutePath(
      created.libraryId, contactSheet!.artifactId,
    );

    const imageBase64 = readFileSync(posterAbsPath).toString('base64');
    const contactSheetBase64 = readFileSync(sheetAbsPath).toString('base64');

    // Poster artifact uses the artifact's MIME type (image/jpeg),
    // not the asset's MIME type (video/mp4).
    const requestMime = poster!.mimeType;
    expect(requestMime).toBe('image/jpeg');

    // 3) Collect existing tags.
    const existingTagNames = service.listTagNames(created.libraryId);

    const filename = filePath.split(/[/\\]/).pop() ?? 'asset';
    const language = 'en';
    const enabledFields = {
      description: true,
      tags: true,
      rating: false,
    };

    // 4) Build AiAnalysisRequest — verify both imageBase64 and contactSheetBase64
    //    are populated.
    const aiRequest: AiAnalysisRequest = {
      filename,
      mime: requestMime,
      imageBase64,
      contactSheetBase64,
      language,
      enabledFields,
      existingTagNames,
    };

    expect(aiRequest.imageBase64).toBeTruthy();
    expect(aiRequest.contactSheetBase64).toBeTruthy();
    expect(aiRequest.imageBase64).toBe(imageBase64);
    expect(aiRequest.contactSheetBase64).toBe(contactSheetBase64);
    // The mime should be image/jpeg, not video/mp4.
    expect(aiRequest.mime).toBe('image/jpeg');

    // 5) Create the adapter with mock fetch and call analyze.
    const mockFetch = mockOpenAiFetchForAnalysis(MOCK_AI_RESPONSE);
    const adapter = new OpenAIVendorAdapter('test-key', 'gpt-4o', mockFetch);

    const analysisResult = await adapter.analyze(aiRequest);
    expect(analysisResult.description).toBe('A test video description generated by the mock AI.');
    expect(analysisResult.tags).toEqual(['VideoTag', 'MockAnalysis']);
    expect(analysisResult.modelVersion).toBe('gpt-4o-2024-05-13');

    // 6) Write results via writeAiAnalysisResult.
    const writeResult = service.writeAiAnalysisResult({
      libraryId: created.libraryId,
      assetId,
      description: analysisResult.description,
      tags: analysisResult.tags,
      modelId: 'gpt-4o',
      modelVersion: analysisResult.modelVersion,
      enabledFields,
    });

    expect(writeResult.tagsWritten).toContain('VideoTag');
    expect(writeResult.tagsWritten).toContain('MockAnalysis');
    expect(writeResult.fieldsWritten).toContain('description');

    // 7) Verify AI content persisted.
    const aiContent = service.getAiContent(created.libraryId, assetId);
    const descRow = aiContent.find((c) => c.fieldName === 'description');
    expect(descRow?.value).toBe('A test video description generated by the mock AI.');

    service.closeAll();
  });

  it('writes ai_asset_tags and verifies they have revision_id set', async () => {
    const root = temporaryRoot();
    const service = new LibraryService();
    const created = service.createLibrary({
      displayName: 'VideoTagRev',
      selectedParentPath: root,
    });

    writeFileSync(path.join(root, 'vid.mp4'), 'video-data');
    const importResult = importNoConflict(
      service,
      created.libraryId,
      path.join(root, 'vid.mp4'),
    );
    const assetId = importResult.assets[0]!.assetId;

    const db = new Database(
      path.join(created.libraryPath, '.serpent', 'library.db'),
    );
    const asset = db
      .prepare('SELECT current_revision_id FROM assets WHERE asset_id = ?')
      .get(assetId) as { current_revision_id: string | null };
    const revisionId = asset.current_revision_id!;

    const writeResult = service.writeAiAnalysisResult({
      libraryId: created.libraryId,
      assetId,
      tags: ['TestVidTag'],
      modelId: 'gpt-4o',
      modelVersion: 'v1',
      enabledFields: { description: false, tags: true, rating: false },
    });

    expect(writeResult.tagsWritten).toContain('TestVidTag');

    // Verify revision_id is stored on the AI tag row.
    const tagRows = db
      .prepare(
        `SELECT aat.revision_id, t.name
           FROM ai_asset_tags aat
           JOIN tags t ON t.tag_id = aat.tag_id
          WHERE aat.asset_id = ?`,
      )
      .all(assetId) as Array<{ revision_id: string | null; name: string }>;
    expect(tagRows).toHaveLength(1);
    expect(tagRows[0]!.name).toBe('TestVidTag');
    expect(tagRows[0]!.revision_id).toBe(revisionId);

    db.close();
    service.closeAll();
  });
});

